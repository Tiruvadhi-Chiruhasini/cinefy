-- Reference schema for Cinefy (PostgreSQL).
-- Hibernate creates this automatically with DDL_AUTO=update. This file documents it and can be
-- used as the starting point for a Flyway migration (V1__init.sql) when you move to production.

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    email       VARCHAR(150) NOT NULL,
    created_at  TIMESTAMP    NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE movies (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         VARCHAR(200)  NOT NULL,
    description   VARCHAR(2000),
    genre         VARCHAR(50)   NOT NULL,
    release_year  INTEGER       NOT NULL,
    poster_url    VARCHAR(500),
    created_at    TIMESTAMP     NOT NULL
);
CREATE INDEX idx_movies_genre ON movies (genre);

CREATE TABLE ratings (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT    NOT NULL,
    movie_id    BIGINT    NOT NULL,
    rating      INTEGER   NOT NULL,
    created_at  TIMESTAMP NOT NULL,
    CONSTRAINT fk_rating_user  FOREIGN KEY (user_id)  REFERENCES users (id),
    CONSTRAINT fk_rating_movie FOREIGN KEY (movie_id) REFERENCES movies (id),
    CONSTRAINT uk_rating_user_movie UNIQUE (user_id, movie_id),
    CONSTRAINT ck_rating_range CHECK (rating BETWEEN 1 AND 5)
);
CREATE INDEX idx_ratings_movie ON ratings (movie_id);
CREATE INDEX idx_ratings_user  ON ratings (user_id);
